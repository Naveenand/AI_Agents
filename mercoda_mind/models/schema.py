from operator import add
from typing import Annotated, Literal

from pydantic import BaseModel, Field


# ------------------------------------------------------------------ SQL agent (yours, unchanged)

class AgentSchema(BaseModel):
    messages : list = Field(default_factory=list, description="To store the AI and Users messages")
    user_question : str = Field(..., description='the user original question')
    curated_ques  : str = Field("", description='Changing the user prompt to structure prompt that AI can understand')
    prompt_query_context : str = Field("", description='the prompt that convert the curated query to sql query from given sql database context')
    generated_sql_query  : str = Field("", description='the sql query created from the curated query')
    is_safe : Literal["Yes","No"] = Field("No", description="Indicates whether the generated SQL query passed the parser safety check")
    comments : str = Field("", description="Reason from the latest check (safety or quality)")
    sql_query_execution_result : str = Field("", description="The result of executing the generated SQL query on the database")
    final_answer : str = Field("", description="The final answer generated by the agent based on the SQL query execution result and the curated question")
    error_message : str = Field("", description="Why the last attempt failed (safety check, database error, or quality check). Empty when nothing is wrong")
    retry_count : int = Field(0, description="How many times the LLM has rewritten the query")
    quality_ok : Literal["Yes","No",""] = Field("", description="Whether the quality check says the query answers the question")


class JudgeSchema(BaseModel):
    comments : str = Field(..., description="Your reasoning first: whether the query is correct, and if not, exactly what to change")
    answer : Literal["Yes","No"] = Field(..., description="Yes if the query correctly answers the user's question, No if it needs fixing")


# ------------------------------------------------------------------ ETL agent

class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(..., description="Chat history: user, AI and tool messages")
    step_count: int = Field(0, description="How many times the LLM has run for the current request (safety limit)")


# ------------------------------------------------------------------ Data Agent (router)

class RouterSchema(BaseModel):
    comments: str = Field(..., description="Your reasoning first: what the user wants, and which agent can do it")
    answer: Literal["sql", "etl", "clarify"] = Field(..., description=(
        "sql = a question answered from the company database; "
        "etl = download from an API, work with data files, or manage pipelines; "
        "clarify = the request is too unclear to choose"))
    clarifying_question: str = Field("", description="Only when answer is 'clarify': one short question to ask the user")


class DataAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(default_factory=list, description="The clean conversation: the user's messages and the final answers only")
    route_response: str = Field("", description="Which agent handled the latest message: sql, etl or clarify")
    clarifying_question: str = Field("", description="The router's question when the request was unclear")
    etl_messages: list = Field(default_factory=list, description="The ETL agent's own full history (tool calls and results), so follow-ups like 'save this' work")
    last_sql: str = Field("", description="The SQL query generated for the latest SQL question, for transparency")
    last_error: str = Field("", description="Error from the latest sub-agent run, if any")
